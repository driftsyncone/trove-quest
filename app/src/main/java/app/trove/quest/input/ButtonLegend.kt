/** What the legend panel shows: the lines for each controller, or the first-run coach card. */
class LegendModel {
  var title by mutableStateOf("")
  var left by mutableStateOf<List<ControlScheme.LegendLine>>(emptyList())
  var right by mutableStateOf<List<ControlScheme.LegendLine>>(emptyList())

  /** First run: the four coach lines instead of the per-hand lines. */
  var coach by mutableStateOf(false)

  /** A short notice ("5 min left") instead of the lines: the session timer's, when nothing else shows it. */
  var notice by mutableStateOf<String?>(null)
}

/**
 * The button legend (docs/control-scheme.md section 6): a small panel in front of you with what each
 * button of each controller does right now, generated by [ControlScheme.legend] from the same rules
 * the router runs. Shown by a stick press (5 s, a second press hides it) and, once, on the first
 * launch of this version (the coach card). Never shown in Black Out. It follows no hand: it is put
 * in front of you when it appears (the doc's attach-to-controller placement is not possible here
 * without a controller-attached transform; this is the fallback it names).
 *
 * [entity]: the legend panel entity (hidden between uses). [place]: where to put it when it shows.
 */
class ButtonLegend(
    private val entity: () -> Entity?,
    private val place: () -> Pose,
) {
  val model = LegendModel()
  private val timer = LegendTimer()
  private var shown = false
  private var refreshedAt = 0L

  /** Stick press: shows the legend for [LegendTimer.SHOW_MS], or hides it when it is up. */
  fun toggle(nowMs: Long, s: Snapshot) {
    model.coach = false
    model.notice = null
    timer.toggle(nowMs)
    refresh(nowMs, s)
  }

  /** First launch of this version: the coach card, longer. */
  fun showCoach(nowMs: Long) {
    model.coach = true
    model.notice = null
    model.title = "New controls"
    timer.show(nowMs, LegendTimer.FIRST_RUN_MS)
  }

  /**
   * A short notice in the same panel (one eye-buffer panel, no extra compositor layer) for
   * [NOTICE_MS]: the session timer's warnings while the library and every control panel are hidden.
   * Put in front of you again even when the panel is already up. Never in Black Out ([tick]).
   */
  fun showNotice(nowMs: Long, text: String) {
    model.coach = false
    model.notice = text
    timer.show(nowMs, NOTICE_MS)
    shown = false // re-placed in front on the next tick
  }

  /** Every frame: shows / hides the panel, and keeps the lines current while it is up. */
  fun tick(nowMs: Long, s: Snapshot) {
    val want = timer.visible(nowMs) && !s.blackout
    if (want && !model.coach && model.notice == null && nowMs - refreshedAt >= REFRESH_MS) refresh(nowMs, s)
    if (!timer.visible(nowMs)) model.notice = null
    if (want == shown) return
    shown = want
    val e = entity() ?: return
    if (want) e.setComponent(Transform(place()))
    e.setComponent(Visible(want))
  }

  private fun refresh(nowMs: Long, s: Snapshot) {
    refreshedAt = nowMs
    val l = ControlScheme.legend(s, Hand.LEFT)
    val r = ControlScheme.legend(s, Hand.RIGHT)
    model.title = ControlScheme.contextOf(s).title
    // The trigger line and the escape are the same on both hands: said once, in the right column / footer.
    model.left = l.filter { it.input != "Trigger" && it.input != ESCAPE }
    model.right = r.filter { it.input != ESCAPE }
  }

  companion object {
    const val ESCAPE = "Both grips 2 s"
    const val REFRESH_MS = 250L
    const val NOTICE_MS = 5_000L
    const val WIDTH_M = 0.96f
    const val HEIGHT_M = 0.5f
  }
}

@Composable
fun ButtonLegendPanel(model: LegendModel) {
  StashTheme {
    model.notice?.let {
      // Small and centred; the rest of the (transparent) panel stays see-through.
      Box(Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
        Text(
            it,
            style = MaterialTheme.typography.titleMedium,
            color = Palette.text,
            modifier = Modifier.clip(RoundedCornerShape(Radius.controlsPanel)).background(Palette.panel).padding(horizontal = Space.xl, vertical = Space.md),
        )
      }
      return@StashTheme
    }
    Column(
        Modifier.fillMaxSize().clip(RoundedCornerShape(Radius.controlsPanel)).background(Palette.panel).padding(Space.lg),
        verticalArrangement = Arrangement.spacedBy(Space.sm),
    ) {
      Text(model.title, style = MaterialTheme.typography.titleSmall, color = Palette.accent)
      if (model.coach) {
        for (line in Coach.lines) LegendRow(line.input, line.text, Modifier.width(COACH_INPUT_W))
      } else {
        Row(horizontalArrangement = Arrangement.spacedBy(Space.xl)) {
          Column(Modifier.weight(1f), verticalArrangement = Arrangement.spacedBy(Space.xs)) {
            Text("Left", style = MaterialTheme.typography.labelMedium, color = Palette.muted)
            for (l in model.left) LegendRow(l.input, l.text, Modifier.width(INPUT_W))
          }
          Column(Modifier.weight(1f), verticalArrangement = Arrangement.spacedBy(Space.xs)) {
            Text("Right", style = MaterialTheme.typography.labelMedium, color = Palette.muted)
            for (l in model.right) LegendRow(l.input, l.text, Modifier.width(INPUT_W))
          }
        }
      }
      LegendRow(ButtonLegend.ESCAPE, "Stop everything and show the room", Modifier.width(if (model.coach) COACH_INPUT_W else INPUT_W), warn = true)
    }
  }
}

@Composable
private fun LegendRow(input: String, text: String, inputModifier: Modifier, warn: Boolean = false) {
  Row(horizontalArrangement = Arrangement.spacedBy(Space.sm)) {
    Text(input, style = MaterialTheme.typography.labelMedium, fontWeight = FontWeight.Bold, color = if (warn) Palette.warn else Palette.accent, modifier = inputModifier)
    Text(text, style = MaterialTheme.typography.bodySmall, color = Palette.text, modifier = Modifier.weight(1f))
  }
}

private val INPUT_W = 124.dp
private val COACH_INPUT_W = 170.dp
